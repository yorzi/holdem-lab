import {
  Action,
  applyAction,
  createInitialHand,
  GameState,
  PlayerId,
  Seat
} from '../domain/betting/holdem'
import { cardKey } from '../domain/cards/cards'
import { HandRank } from '../domain/showdown/hand-evaluator'
import type { DecisionRecord } from '../domain/records/decision-record'
import { RNG_ALGORITHM_VERSION } from '../domain/rng/seeded-rng'
import { HAND_EVALUATOR_VERSION, HOLDEM_RULES_VERSION } from '../domain/versions'

export const REPLAY_FORMAT_VERSION = 'holdem-replay-v2'

export class UnsupportedReplayVersionError extends Error {
  readonly code: string

  constructor(code: string, message: string) {
    super(message)
    this.name = 'UnsupportedReplayVersionError'
    this.code = code
  }
}

export interface ReplayStep {
  readonly actor: PlayerId
  readonly action: Action
}

export interface ReplayOptions {
  readonly heroSeat?: Seat
  readonly startingStack?: number
  readonly smallBlind?: number
  readonly bigBlind?: number
}

export interface ReplayInput {
  readonly seed: string
  readonly actions: readonly ReplayStep[]
  readonly options?: ReplayOptions
}

const REPLAYABLE_ACTION_TYPES: ReadonlySet<Action['type']> = new Set([
  'fold',
  'check',
  'call',
  'bet',
  'raise',
  'allIn'
])

/**
 * Replays a deterministic action trace through the one canonical TypeScript
 * Hold'em engine. Ruby does not reimplement this state machine.
 */
export function replayHand(input: ReplayInput): GameState {
  let state = createInitialHand({ seed: input.seed, ...input.options })

  input.actions.forEach((step, index) => {
    const result = applyAction(state, step.actor, step.action)
    if (!result.ok) {
      throw new Error(`Replay step ${index + 1} failed: ${result.error.code} — ${result.error.message}`)
    }
    state = result.state
  })

  return state
}

function isReplayableActionEntry(entry: GameState['actionHistory'][number]): entry is GameState['actionHistory'][number] & {
  readonly actor: PlayerId
  readonly type: Action['type']
} {
  return (entry.actor === 'hero' || entry.actor === 'villain') && REPLAYABLE_ACTION_TYPES.has(entry.type as Action['type'])
}

/**
 * Converts an immutable DecisionRecord into the smallest deterministic input
 * needed by the canonical engine. System entries (blinds, deals and returns)
 * are regenerated by the engine; bet/raise entries use targetContribution
 * because Action.amount is a target, while ActionEntry.amount is the amount
 * paid during that action.
 */
export function replayInputForDecisionRecord(record: DecisionRecord): ReplayInput {
  assertReplayCompatibility(record)
  const actions = record.resultState.actionHistory
    .filter(isReplayableActionEntry)
    .map((entry, index): ReplayStep => {
      if (entry.type === 'bet' || entry.type === 'raise') {
        if (entry.targetContribution === undefined) {
          throw new TypeError(`Replay action ${index + 1} is missing its target contribution`)
        }
        return { actor: entry.actor, action: { type: entry.type, amount: entry.targetContribution } }
      }

      return { actor: entry.actor, action: { type: entry.type } }
    })

  return {
    seed: record.seed,
    options: {
      heroSeat: record.snapshot.heroSeat,
      startingStack: record.snapshot.startingStack,
      smallBlind: record.snapshot.smallBlind,
      bigBlind: record.snapshot.bigBlind
    },
    actions
  }
}

export interface DecisionRecordReplay {
  readonly input: ReplayInput
  readonly state: GameState
  readonly matchesResult: boolean
}

/** Replays a saved record and compares the result with its immutable snapshot. */
export function replayDecisionRecord(record: DecisionRecord): DecisionRecordReplay {
  assertReplayCompatibility(record)
  const input = replayInputForDecisionRecord(record)
  const state = replayHand(input)
  return {
    input,
    state,
    matchesResult: replayFingerprint(state) === replayFingerprint(record.resultState)
  }
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function requireVersion(value: unknown, expected: string | number, code: string, label: string): void {
  if (value !== expected) {
    throw new UnsupportedReplayVersionError(code, `${label} ${String(value)} is not supported; expected ${expected}.`)
  }
}

/** Routes only current records to the v2 engine; v1 is preserved but rejected. */
export function assertReplayCompatibility(value: unknown): asserts value is DecisionRecord {
  if (!isRecord(value)) {
    throw new UnsupportedReplayVersionError('malformed_record', 'Replay record is malformed.')
  }
  requireVersion(value.version, 2, 'record_version', 'DecisionRecord version')
  requireVersion(value.ruleVersion, HOLDEM_RULES_VERSION, 'rule_version', 'Rules version')
  requireVersion(value.evaluatorVersion, HAND_EVALUATOR_VERSION, 'evaluator_version', 'Evaluator version')
  requireVersion(value.rngAlgorithmVersion, RNG_ALGORITHM_VERSION, 'rng_version', 'RNG version')

  for (const [label, state] of [['snapshot', value.snapshot], ['resultState', value.resultState]] as const) {
    if (!isRecord(state)) {
      throw new UnsupportedReplayVersionError('malformed_state', `${label} is malformed.`)
    }
    requireVersion(state.ruleVersion, HOLDEM_RULES_VERSION, 'state_rule_version', `${label} rules version`)
    requireVersion(state.evaluatorVersion, HAND_EVALUATOR_VERSION, 'state_evaluator_version', `${label} evaluator version`)
    requireVersion(state.rngAlgorithmVersion, RNG_ALGORITHM_VERSION, 'state_rng_version', `${label} RNG version`)
  }
}

function parseAction(value: unknown, index: number): ReplayStep {
  if (!isRecord(value) || !isRecord(value.action) || (value.actor !== 'hero' && value.actor !== 'villain')) {
    throw new TypeError(`Replay action ${index + 1} is malformed`)
  }

  const actionType = value.action.type
  const actionTypes: readonly Action['type'][] = ['fold', 'check', 'call', 'bet', 'raise', 'allIn']
  if (typeof actionType !== 'string' || !actionTypes.includes(actionType as Action['type'])) {
    throw new TypeError(`Replay action ${index + 1} has an unknown action type`)
  }

  let amount: number | undefined
  if ('amount' in value.action) {
    if (typeof value.action.amount !== 'number' || !Number.isInteger(value.action.amount)) {
      throw new TypeError(`Replay action ${index + 1} has an invalid amount`)
    }
    amount = value.action.amount
  }

  const action: Action = amount === undefined
    ? { type: actionType as Action['type'] }
    : { type: actionType as Action['type'], amount }
  return { actor: value.actor, action }
}

function parseOptions(value: unknown): ReplayOptions | undefined {
  if (value === undefined || value === null) {
    return undefined
  }
  if (!isRecord(value)) {
    throw new TypeError('Replay options are malformed')
  }

  const options: { heroSeat?: Seat; startingStack?: number; smallBlind?: number; bigBlind?: number } = {}
  if ('heroSeat' in value) {
    if (value.heroSeat !== 'button' && value.heroSeat !== 'bigBlind') {
      throw new TypeError('Replay heroSeat is malformed')
    }
    options.heroSeat = value.heroSeat
  }

  for (const key of ['startingStack', 'smallBlind', 'bigBlind'] as const) {
    if (key in value) {
      if (typeof value[key] !== 'number' || !Number.isInteger(value[key])) {
        throw new TypeError(`Replay ${key} is malformed`)
      }
      options[key] = value[key]
    }
  }

  return options
}

/** Serialize only deterministic replay inputs; do not persist runtime objects or secrets. */
export function serializeReplay(input: ReplayInput): string {
  return JSON.stringify({
    version: REPLAY_FORMAT_VERSION,
    ruleVersion: HOLDEM_RULES_VERSION,
    evaluatorVersion: HAND_EVALUATOR_VERSION,
    rngAlgorithmVersion: RNG_ALGORITHM_VERSION,
    seed: input.seed,
    options: input.options ?? null,
    actions: input.actions.map((step) => ({
      actor: step.actor,
      action: step.action.amount === undefined
        ? { type: step.action.type }
        : { type: step.action.type, amount: step.action.amount }
    }))
  })
}

/** Parse the versioned replay input and reject malformed or unknown action data. */
export function deserializeReplay(serialized: string): ReplayInput {
  let parsed: unknown
  try {
    parsed = JSON.parse(serialized) as unknown
  } catch {
    throw new TypeError('Replay is not valid JSON')
  }

  if (!isRecord(parsed) || parsed.version !== REPLAY_FORMAT_VERSION || typeof parsed.seed !== 'string' || !Array.isArray(parsed.actions)) {
    throw new TypeError('Replay has an unsupported or malformed format')
  }
  requireVersion(parsed.ruleVersion, HOLDEM_RULES_VERSION, 'rule_version', 'Replay rules version')
  requireVersion(parsed.evaluatorVersion, HAND_EVALUATOR_VERSION, 'evaluator_version', 'Replay evaluator version')
  requireVersion(parsed.rngAlgorithmVersion, RNG_ALGORITHM_VERSION, 'rng_version', 'Replay RNG version')

  return {
    seed: parsed.seed,
    options: parseOptions(parsed.options),
    actions: parsed.actions.map((action, index) => parseAction(action, index))
  }
}

function rankFingerprint(rank: HandRank | null): object | null {
  if (rank === null) {
    return null
  }

  return {
    category: rank.category,
    categoryValue: rank.categoryValue,
    tiebreakers: [...rank.tiebreakers],
    cards: rank.cards.map(cardKey)
  }
}

/**
 * Produces a stable, bounded replay contract for parity tests and future
 * persisted DecisionRecord snapshots. It intentionally includes the deck so a
 * seed or shuffle algorithm change cannot silently alter a replay.
 */
export function replayFingerprint(state: GameState): string {
  const fingerprint = {
    version: REPLAY_FORMAT_VERSION,
    seed: state.seed,
    rngAlgorithmVersion: state.rngAlgorithmVersion,
    ruleVersion: state.ruleVersion,
    evaluatorVersion: state.evaluatorVersion,
    heroSeat: state.heroSeat,
    startingStack: state.startingStack,
    smallBlind: state.smallBlind,
    bigBlind: state.bigBlind,
    street: state.street,
    phase: state.phase,
    currentActor: state.currentActor,
    players: {
      hero: {
        seat: state.players.hero.seat,
        stack: state.players.hero.stack,
        holeCards: state.players.hero.holeCards.map(cardKey),
        streetContribution: state.players.hero.streetContribution,
        totalContribution: state.players.hero.totalContribution,
        folded: state.players.hero.folded,
        allIn: state.players.hero.allIn
      },
      villain: {
        seat: state.players.villain.seat,
        stack: state.players.villain.stack,
        holeCards: state.players.villain.holeCards.map(cardKey),
        streetContribution: state.players.villain.streetContribution,
        totalContribution: state.players.villain.totalContribution,
        folded: state.players.villain.folded,
        allIn: state.players.villain.allIn
      }
    },
    publicCards: state.publicCards.map(cardKey),
    deck: state.deck.map(cardKey),
    nextCardIndex: state.nextCardIndex,
    pot: state.pot,
    lastFullRaise: state.lastFullRaise,
    lastAggressor: state.lastAggressor,
    actedSinceAggression: [...state.actedSinceAggression],
    actionHistory: state.actionHistory.map((entry) => ({
      sequence: entry.sequence,
      actor: entry.actor,
      type: entry.type,
      street: entry.street,
      amount: entry.amount,
      targetContribution: entry.targetContribution ?? null,
      potAfter: entry.potAfter,
      note: entry.note ?? null
    })),
    showdown: state.showdown === null
      ? null
      : {
          reason: state.showdown.reason,
          totalPot: state.showdown.totalPot,
          winnerIds: [...state.showdown.winnerIds],
          payouts: { ...state.showdown.payouts },
          pots: state.showdown.pots.map((pot) => ({
            amount: pot.amount,
            cap: pot.cap,
            eligiblePlayerIds: [...pot.eligiblePlayerIds]
          })),
          handRanks: {
            hero: rankFingerprint(state.showdown.handRanks.hero),
            villain: rankFingerprint(state.showdown.handRanks.villain)
          }
        }
  }

  return JSON.stringify(fingerprint)
}
